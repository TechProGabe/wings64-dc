/* db.h — debug knobs. Every knob is a compile-time DB_* define, OFF by default, so the
 * default build is the good build. Turn one on with:  EXTRA_CFLAGS=-DDB_LOG_SD=1 ./run.sh disc
 * RELEASE=1 builds force DB_ENABLE=0 and drop db.o's optional paths.
 *
 *   DB_ENABLE     master switch for db_log output (serial / dcload console). Default 1, release 0.
 *   DB_LOG_SD     mirror db_log to /sd/wings64/log-<buildid>.txt via the SD card adapter
 *                 (FAT, first MBR partition). Never required; silently off if no card. Default 0.
 *   DB_PERF       on-screen per-phase timings (M2+). Default 0.
 *   DB_BOOT_LEVEL skip menus and boot straight into a level (M2+). Default -1 (off).
 */
#ifndef WINGS64_DB_H
#define WINGS64_DB_H

#ifndef DB_ENABLE
#define DB_ENABLE 1
#endif
#ifndef DB_LOG_SD
#define DB_LOG_SD 0
#endif
#ifndef DB_PERF
#define DB_PERF 0
#endif
#ifndef DB_BOOT_LEVEL
#define DB_BOOT_LEVEL (-1)
#endif

#if DB_LOG_SD && !DB_ENABLE
#error "DB_LOG_SD needs DB_ENABLE"
#endif

/* Build stamp generated by scripts/build_target.sh into build/dc/stamp.h. */
extern const char wings64_build_id[];

#if DB_ENABLE
void db_log(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
#else
#define db_log(...) ((void)0)
#endif

/* Mount the SD log (no-op unless DB_LOG_SD). Returns 1 if the SD log is active. */
int db_sd_init(void);
/* Push buffered log text to the SD card (no-op unless DB_LOG_SD). Cheap when nothing pending. */
void db_sd_flush(void);

#endif
